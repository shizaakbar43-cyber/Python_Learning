# Arithmetic Operators
x = 10
y = 5
print("Sum : ",x+y)
print("Sub: " ,x-y)
print("Multiply: " ,x*y)
print("Divide: " ,x/y)
print("Modulus: " ,x%y)
print("Exponent: " ,x**y)
# take input from user 
a = float(input("Enter a first number: "))
b = float(input("Enter a second number: "))
print("Sum : ",a+b)
print("Sub: " ,a-b)
print("Multiply: " ,a*b)
print("Divide: " ,a/b)
print("Modulus: " ,a%b)
print("Exponent: " ,a**b)

#Logical Operators
x = True
y = False
print("x AND y: ", x and y)
print("x OR y: ", x or y)
print("NOT x: ", not x)
# take input from user in boolean
a = bool(input("Enter a first boolean value : "))
b = bool(input("Enter a second boolean value: "))
print("a AND b: ", a and b)
print("a OR b: ", a or b)
print("NOT a: ", not a)

#Comparison OOperators
x = 10
y = 5
print("X is greater than Y : ", x > y)
print("X is less than Y: ", x < y)
print("X is equal to Y: ", x == y)
print("X is not equal to Y: ", x != y)
print("X is greater than or equal to Y: ", x >= y)
print("X is less than or equal to Y: ", x <= y)

